// gcec local check: the `ours` merge driver carries GENERATED artifacts only —
// never a file a person writes. This is the OTHER direction of the list
// regen-artifacts-merge-ours.mjs guards: that rule asks "is every regen artifact
// on the driver?", this one asks "is everything on the driver a regen artifact?".
// The rule it converts is RULES.md's regen bullet, which states the exception in
// so many words: the inline gallery in `dev/requirements/requirements.md` is
// "part-authored prose — **not** on the `ours` driver; reconcile via `npm run
// regen` + the gallery drift gate". .gitattributes says the same from its side,
// heading the block "Generated/derived files — regenerated by `npm run regen`,
// never hand-merged."
//
// Why a check and not just prose: `merge=ours` is the one setting in this repo
// whose misuse DESTROYS AUTHORED WORK IN SILENCE. On a conflicting merge the
// driver doesn't raise a conflict — it keeps our side and drops theirs, with no
// marker, no prompt and nothing red. On a generated file that is the whole point
// (you rerun the generator). On an authored one it is data loss: the other
// branch's prose is gone, the merge reports success, and every suite stays green
// because the file still parses. Nobody finds it until a reviewer notices their
// paragraph vanished.
//
// And the misuse is a plausible edit, not a far-fetched one. Every entry in the
// block is a glob, and requirements.md sits INSIDE the very tree the block
// already names (dev/requirements/): one well-meant widening —
// `dev/requirements/**/* merge=ours`, or a `*.md merge=ours` reaching the
// GENERATED coverage report — silently swallows the part-authored gallery file,
// which is regenerated in part and therefore looks generated at a glance. The
// existing check cannot see this: it only ever asks whether artifacts are
// PRESENT on the driver, so a pattern that over-reaches is invisible to it.
//
// WHAT COUNTS AS GENERATED is imported, not restated (isGeneratedArtifact) — the
// union of the uppercase GENERATED marker, the lowercase `.generated.`
// convention and the auto-discovered `<kind>/cases/*.png` snapshots. Sharing one
// definition is the point: the two halves of a single list must not disagree
// about whether a given file belongs on the driver.
//
// Local-pack check modules are dependency-free on purpose (see
// test-offline-list-sync.mjs's header): plain finding objects, no engine imports,
// so they also load under the repo's own `npm test` (pack.test.mjs).
import { isGeneratedArtifact, oursPatterns, matchingOursPattern } from './regen-artifacts-merge-ours.mjs';

const id = 'merge-ours-generated-only';
const severity = 'blocking';
const doc = '.claudinite/local/packs/gcec/RULES.md';
const why =
  'the `ours` driver resolves a conflicting merge by silently discarding the other side — on an ' +
  'authored file that is lost work with no conflict, no marker and every suite still green';

export default {
  id,
  severity,
  description: 'only generated artifacts sit on the `ours` merge driver in .gitattributes',
  doc,
  why,

  run(ctx) {
    // allFiles, not files: this rule reasons ABOUT the generated/authored split,
    // so it must still see artifacts the repo may mark linguist-generated (which
    // the engine otherwise drops from ctx.files) — otherwise a generated file
    // would look "authored" here purely by being absent. Falls back to ctx.files
    // for a context that doesn't draw the distinction.
    const all = ctx.allFiles || ctx.files || [];
    if (!all.length) return [];

    const patterns = oursPatterns(ctx.read('.gitattributes'));
    if (!patterns.length) return [];

    // Only committed files are judged. A pattern matching nothing is not a
    // finding: it is either a not-yet-created artifact or dead weight, and
    // neither loses anyone's work. Under a --changed run `all` narrows, which
    // only ever under-reports.
    return all
      .filter((file) => !isGeneratedArtifact(file))
      .map((file) => ({ file, hit: matchingOursPattern(patterns, file) }))
      .filter(({ hit }) => hit)
      .map(({ file, hit }) => ({
        rule: id,
        severity,
        file,
        line: null,
        what: `${file} is authored by hand but \`${hit.pattern} merge=ours\` puts it on the \`ours\` merge driver`,
        why,
        fix:
          `narrow or remove the \`${hit.pattern}\` entry in .gitattributes so it reaches only generated ` +
          'artifacts — a part-authored file (the inline gallery in dev/requirements/requirements.md is ' +
          'the one this repo has) is reconciled by rerunning `npm run regen` and letting its drift gate ' +
          'fail, never by having git throw the other side away',
        doc,
      }));
  },
};
